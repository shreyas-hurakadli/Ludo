package com.shreyashurakadli.multiplayer

import android.content.Context
import com.shreyashurakadli.multiplayer.transport.Role
import com.shreyashurakadli.multiplayer.transport.Transport
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.channels.ReceiveChannel
import kotlinx.coroutines.flow.SharingStarted
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.map
import kotlinx.coroutines.flow.stateIn
import kotlinx.coroutines.job

internal class Room(
    private val transport: Transport,
    private val role: Role,
    private val scope: CoroutineScope
) {
    companion object {
        internal const val DEFAULT_EXPECTED_PLAYER_COUNT = Transport.DEFAULT_EXPECTED_PEER_COUNT
        private const val MIN_ROOM_SIZE = 2U
        private const val MAX_ROOM_SIZE = 4U

        fun create(
            context: Context,
            name: String,
            role: Role,
            protocol: Protocol,
            scope: CoroutineScope
        ): Room {
            val transport = Transport.create(
                context = context,
                name = name,
                protocol = protocol
            )
            val roomScope = CoroutineScope(
                scope.coroutineContext + SupervisorJob(scope.coroutineContext.job)
            )

            return Room(transport, role, roomScope)
        }
    }

    val players: StateFlow<List<Player>> =
        transport.peers
            .map { peerList ->
                peerList.map { peer -> peer.toPlayer() }
            }
            .stateIn(
                scope = scope,
                started = SharingStarted.WhileSubscribed(TIMEOUT_MILLIS),
                initialValue = emptyList()
            )

    val incomingMessage: ReceiveChannel<ReceivedMessage> = transport.incomingMessage

    /**
     * Binds the room code and starts the transport.
     * Call only once the code is known: typed by the guest, generated by the host.
     *
     * @param playerCount Total players including self (2..4); the guest may use the
     *   default and correct it later via [updatedPlayerCount].
     */
    fun enter(token: String, playerCount: UInt = DEFAULT_EXPECTED_PLAYER_COUNT) {
        require(playerCount in MIN_ROOM_SIZE..MAX_ROOM_SIZE) {
            "Expected player count must be between $MIN_ROOM_SIZE and $MAX_ROOM_SIZE"
        }
        transport.setToken(token)
        transport.start(role = role, peerCount = playerCount)
    }

    /**
     * Corrects the expected lobby size after [enter], e.g. when the guest learns it from the host.
     */
    fun updatedPlayerCount(count: UInt) {
        require(count in MIN_ROOM_SIZE..MAX_ROOM_SIZE) {
            "Expected player count must be between $MIN_ROOM_SIZE and $MAX_ROOM_SIZE"
        }
        transport.setPeerCount(count)
    }

    fun checkPrerequisites(): PrerequisitesResult = transport.checkPrerequisites()

    fun communicate(player: Player, message: String) {
        transport.sendPayload(player.id, message)
    }

    fun close() {
        scope.cancel()
        transport.close()
    }
}
