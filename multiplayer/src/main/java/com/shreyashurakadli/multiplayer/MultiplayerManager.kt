package com.shreyashurakadli.multiplayer

import android.content.Context
import com.shreyashurakadli.multiplayer.transport.Role
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.channels.ReceiveChannel
import kotlinx.coroutines.flow.StateFlow

internal const val TIMEOUT_MILLIS = 5_000L

class MultiplayerManager private constructor(
    private val room: Room
) {
    val players: StateFlow<List<Player>> = room.players

    /**
     * Mailbox of messages received from peers, in arrival order.
     * Exactly one consumer must collect it for this manager's lifetime.
     */
    val incomingMessage: ReceiveChannel<ReceivedMessage> = room.incomingMessage

    companion object {
        fun create(
            name: String,
            role: Role,
            context: Context,
            protocol: Protocol,
            scope: CoroutineScope
        ): MultiplayerManager {
            val room = Room.create(
                context = context,
                name = name,
                role = role,
                protocol = protocol,
                scope = scope
            )

            return MultiplayerManager(room)
        }
    }

    fun checkPrerequisites(): PrerequisitesResult = room.checkPrerequisites()

    /**
     * Starts advertising (host) or discovery (guest) for the room identified by [token].
     *
     * @param token Room code: generated by the host, typed by the guest.
     * @param playerCount Total players including self (2..4); the guest may omit it
     *   and correct it later via [updatedPlayerCount].
     */
    fun start(
        token: String,
        playerCount: UInt = Room.DEFAULT_EXPECTED_PLAYER_COUNT
    ) {
        room.enter(token = token, playerCount = playerCount)
    }

    /**
     * Corrects the expected lobby size after [start], e.g. when the guest learns it from the host.
     */
    fun updatedPlayerCount(count: UInt) {
        room.updatedPlayerCount(count)
    }

    fun sendMessage(player: Player, message: String) {
        room.communicate(player, message)
    }

    fun leaveRoom() {
        room.close()
    }
}
